package dev.quokkify.mongodb.steps;

import java.util.List;
import java.util.Objects;

import dev.quokkify.mongodb.query.MongoQuery;
import dev.quokkify.mongodb.service.MongoFactory;
import dev.quokkify.mongodb.verification.MongoVerifier;
import dev.quokkify.step.AbstractSteps;

import com.mongodb.client.model.Filters;
import com.mongodb.client.model.Updates;
import com.mongodb.client.result.DeleteResult;
import com.mongodb.client.result.UpdateResult;
import com.querydsl.core.types.EntityPath;
import io.qameta.allure.Step;
import org.bson.BsonDocument;
import org.bson.BsonDocumentWriter;
import org.bson.BsonValue;
import org.bson.codecs.Codec;
import org.bson.codecs.EncoderContext;
import org.bson.conversions.Bson;

/**
 * Steps for saving, updating, deleting and querying MongoDB documents in tests.
 */
public class MongoDatabaseSteps extends AbstractSteps<MongoVerifier> {

  private static final String ID_FIELD = "_id";

  private final MongoFactory factory;

  public MongoDatabaseSteps(MongoFactory factory) {
    this.factory = Objects.requireNonNull(factory, "factory");
  }

  /**
   * Insert the entity. A null {@code @BsonId} is generated by the driver and written back to the entity.
   *
   * @param entity document to save
   * @param <T> document type
   */
  @Step("Save entity to mongo database")
  @SuppressWarnings("unchecked")
  public <T> void save(T entity) {
    factory.collection((Class<T>) entity.getClass()).insertOne(entity);
  }

  /**
   * Insert the entities; an empty list does nothing.
   *
   * @param entities documents to save
   * @param <T> document type
   */
  @Step("Save entities to mongo database")
  @SuppressWarnings("unchecked")
  public <T> void save(List<T> entities) {
    if (entities.isEmpty()) {
      return;
    }
    factory.collection((Class<T>) entities.get(0).getClass()).insertMany(entities);
  }

  /**
   * Apply the update operations to the stored document with the same {@code _id}.
   *
   * @param entity saved document
   * @param updates update operations, at least one
   * @param <T> document type
   * @return update result
   * @throws IllegalArgumentException if there are no operations or the entity has no {@code _id}
   */
  @Step("Update entity in mongo database")
  public <T> UpdateResult update(T entity, Bson... updates) {
    if (updates.length == 0) {
      throw new IllegalArgumentException("update requires at least one update operation");
    }
    return factory.documents(entity.getClass())
        .updateOne(Filters.eq(ID_FIELD, idOf(entity)), Updates.combine(updates));
  }

  /**
   * Delete the stored document with the same {@code _id}.
   *
   * @param entity saved document
   * @param <T> document type
   * @return delete result
   * @throws IllegalArgumentException if the entity has no {@code _id}
   */
  @Step("Delete entity in mongo database")
  public <T> DeleteResult delete(T entity) {
    return factory.documents(entity.getClass()).deleteOne(Filters.eq(ID_FIELD, idOf(entity)));
  }

  /**
   * Create a type-safe query for the documents of the given Q-class.
   *
   * @param path generated Querydsl entity path
   * @param <T> document type
   * @return query
   */
  @Step("Create query for mongo database")
  @SuppressWarnings("unchecked")
  public <T> MongoQuery<T> selectQuery(EntityPath<T> path) {
    return new MongoQuery<>(factory, (Class<T>) path.getType());
  }

  /**
   * Start a verification chain.
   *
   * @return verifier
   */
  @Override
  public MongoVerifier verify() {
    return new MongoVerifier();
  }

  @SuppressWarnings("unchecked")
  private BsonValue idOf(Object entity) {
    Codec<Object> codec = (Codec<Object>) factory.codecRegistry().get(entity.getClass());
    BsonDocument encoded = new BsonDocument();
    codec.encode(new BsonDocumentWriter(encoded), entity, EncoderContext.builder().build());
    BsonValue id = encoded.get(ID_FIELD);
    if (id == null || id.isNull()) {
      throw new IllegalArgumentException(entity.getClass().getName() + " has no _id; save it first");
    }
    return id;
  }
}
